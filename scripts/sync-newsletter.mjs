#!/usr/bin/env node
/**
 * Pulls Benchmarked issues from a local clone of
 * github.com/poojaverma-me/benchmarked into the site:
 *
 *   content/newsletter/<slug>.html     each issue, untouched (served by
 *                                      app/newsletter/[slug]/route.ts)
 *   content/newsletter/index.html      the contents page (app/newsletter/route.ts)
 *   public/newsletter/<slug>/images/   each issue's images
 *   lib/newsletter.ts                  the issue list, from the contents page
 *
 * Usage: node scripts/sync-newsletter.mjs [path-to-benchmarked-clone]
 * After publishing a new issue in that repo: git pull there, run this, commit.
 */
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync, readdirSync } from "node:fs";
import { homedir } from "node:os";
import { join, resolve } from "node:path";

const ROOT = resolve(import.meta.dirname, "..");
const SRC = resolve(process.argv[2] ?? join(homedir(), "Projects/portfolio-projects/benchmarked"));
const CONTENT = join(ROOT, "content/newsletter");
const PUBLIC = join(ROOT, "public/newsletter");

if (!existsSync(join(SRC, "index.html"))) {
  console.error(`No Benchmarked contents page at ${SRC}/index.html`);
  process.exit(1);
}

const decode = (s) =>
  s
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&#39;|&rsquo;/g, "’")
    .replace(/<[^>]+>/g, "")
    .trim();

// one <a class="issue"> per issue on the contents page, newest first
const contents = readFileSync(join(SRC, "index.html"), "utf8");
const ISSUE =
  /<a class="issue" href="([^"/]+)\/index\.html">\s*<div class="meta">([\s\S]*?)<\/div>\s*<h2>([\s\S]*?)<\/h2>\s*<p>([\s\S]*?)<\/p>\s*<\/a>/g;

const issues = [];
for (const [, slug, meta, title, dek] of contents.matchAll(ISSUE)) {
  const parts = decode(meta).split(" · ");
  const minutes = Number(/(\d+)-minute/.exec(parts.at(-1))?.[1]) || undefined;
  const html = readFileSync(join(SRC, slug, "index.html"), "utf8");
  const firstImage = /<img[^>]+src="images\/([^"]+)"/.exec(html)?.[1];
  issues.push({
    slug,
    title: decode(title),
    dek: decode(dek),
    date: parts[0],
    iso: slug.slice(0, 10),
    kind: parts[1],
    minutes,
    cover: firstImage ? `/newsletter/${slug}/images/${firstImage}` : undefined,
  });
}
if (!issues.length) {
  console.error("Found no issues on the contents page; has its markup changed?");
  process.exit(1);
}

// start clean so deleted issues and images disappear too
rmSync(CONTENT, { recursive: true, force: true });
rmSync(PUBLIC, { recursive: true, force: true });
mkdirSync(CONTENT, { recursive: true });
cpSync(join(SRC, "index.html"), join(CONTENT, "index.html"));
for (const { slug } of issues) {
  cpSync(join(SRC, slug, "index.html"), join(CONTENT, `${slug}.html`));
  const images = join(SRC, slug, "images");
  if (existsSync(images)) cpSync(images, join(PUBLIC, slug, "images"), { recursive: true });
}

writeFileSync(
  join(ROOT, "lib/newsletter.ts"),
  `// Generated by scripts/sync-newsletter.mjs from the Benchmarked repo. Do not edit by hand.

export type Issue = {
  slug: string;
  title: string;
  dek: string;
  /** as printed, e.g. "3 Oct 2026" */
  date: string;
  /** YYYY-MM-DD */
  iso: string;
  /** e.g. "Model launch" */
  kind: string;
  minutes?: number;
  /** the issue's first figure */
  cover?: string;
};

/** newest first */
export const issues: Issue[] = ${JSON.stringify(issues, null, 2)};
`,
);

const imageCount = issues.reduce(
  (n, { slug }) => n + (existsSync(join(PUBLIC, slug, "images")) ? readdirSync(join(PUBLIC, slug, "images")).length : 0),
  0,
);
console.log(`Synced ${issues.length} issues and ${imageCount} images from ${SRC}`);
