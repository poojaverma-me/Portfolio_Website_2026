// Writes lib/projectImages.ts: the pixel size of every image under
// public/projects, so next/image can reserve the right space for screenshots
// referenced by path in lib/projects.ts. Run after adding or replacing images:
//   node scripts/image-manifest.mjs
import { readdir, writeFile } from "node:fs/promises";
import { join, relative } from "node:path";
import sharp from "sharp";

const root = new URL("..", import.meta.url).pathname;
const dir = join(root, "public/projects");

async function walk(d) {
  const out = [];
  for (const e of await readdir(d, { withFileTypes: true })) {
    const p = join(d, e.name);
    if (e.isDirectory()) out.push(...(await walk(p)));
    else if (/\.(webp|png|jpe?g|avif)$/i.test(e.name)) out.push(p);
  }
  return out.sort();
}

const lines = [];
for (const file of await walk(dir)) {
  const { width, height } = await sharp(file).metadata();
  lines.push(`  "/${relative(join(root, "public"), file)}": [${width}, ${height}],`);
}

await writeFile(
  join(root, "lib/projectImages.ts"),
  `// Generated by scripts/image-manifest.mjs. Do not edit by hand.\n` +
    `export const imageSize: Record<string, [number, number]> = {\n${lines.join("\n")}\n};\n`,
);
console.log(`${lines.length} images`);
